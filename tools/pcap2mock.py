#!/usr/bin/env python3
"""Convert a capture (captures/X.pcap + X.txt) into a libmydaq mock-transport replay script.

  pcap2mock.py [--calmem captures/calmem-036CD1C6.bin] [--out DIR] X.pcap [Y.pcap ...]

Script format (one entry per line, event order; read by libmydaq/tests/mock/mock.c):
  > hex    command frame the library must send on EP 0x03 (compared byte for byte)
  < hex    response the device returned on EP 0x81
  e hex    event frame on interrupt EP 0x82
  d hex    sample data on bulk EP 0x84
  @ text   marker (DAQmx step from the .txt: "@ rep 0", ...)
  = v ...  values DAQmx returned (from the .txt DATA lines), for the tests to compare
  # text   comment

QEMU's pcap keeps at most 256 bytes per transfer. Truncated calibration-memory responses are
rebuilt from the calibration dump (and checked against the captured prefix); other truncated
transfers make the conversion fail.
"""
import argparse
import os
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import usbflow  # noqa: E402

R = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
KIND = {0x03: ">", 0x81: "<", 0x82: "e", 0x84: "d"}


def rebuild_calmem_response(request, captured, calmem):
    """Response to `op08 05 07 00 00 <off> <len>`: kind 6, status 0, u16 len+2, data, pad."""
    off, n = struct.unpack(">II", request[12:20])
    body = struct.pack(">II", 6, 0) + struct.pack(">H", n + 2) + calmem[off:off + n]
    total = 8 + len(body)
    total += (-total) % 4
    frame = struct.pack(">HHHBB", 1, total, total - 4, 1, 0) + body
    frame += b"\0" * (total - len(frame))
    if not frame.startswith(captured):
        raise ValueError(f"rebuilt calibration response at {off:#x} does not match the capture")
    return frame


def txt_events(txt_path):
    """(host time, line) for the .txt lines worth keeping."""
    out = []
    if not os.path.exists(txt_path):
        return out
    for line in open(txt_path):
        line = line.rstrip("\n")
        if line.startswith("DATA"):
            out.append("= " + " ".join(line.split()[2:]))
        elif " rep " in line or line.endswith(" end") or " begin " in line or "wrote" in line:
            out.append("@ " + line.split(" ", 1)[1] if " " in line else "@ " + line)
    return out


def convert(pcap, calmem):
    lines = [f"# generated by tools/pcap2mock.py from captures/{os.path.basename(pcap)}"]
    txt = pcap[:-5] + ".txt"
    for line in open(txt) if os.path.exists(txt) else []:
        if line.startswith("# capture"):
            lines.append("# " + line[2:].rstrip())
    last_request = None
    for t, u in usbflow.transfers(pcap, set(KIND)):
        data = bytes(u.data)
        if u.length > len(data):
            if u.ep == 0x81 and last_request is not None and last_request[7] == 0x08 \
                    and last_request[8:12] == bytes.fromhex("05070000"):
                data = rebuild_calmem_response(last_request, data, calmem)
            else:
                raise ValueError(f"{pcap}: transfer on {u.ep:#04x} truncated by the capture "
                                 f"({len(data)} of {u.length} bytes)")
        if u.ep == 0x03:
            last_request = data
        lines.append(f"{KIND[u.ep]} {data.hex()}")
    # DAQmx results in order; tests pick them by position.
    lines.extend(txt_events(txt))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("pcaps", nargs="+")
    ap.add_argument("--calmem", default=os.path.join(R, "captures/calmem-036CD1C6.bin"))
    ap.add_argument("--out", default=os.path.join(R, "libmydaq/tests/data"))
    a = ap.parse_args()
    calmem = open(a.calmem, "rb").read()
    os.makedirs(a.out, exist_ok=True)
    for p in a.pcaps:
        name = os.path.basename(p)[:-5] + ".mock"
        with open(os.path.join(a.out, name), "w") as f:
            f.write(convert(p, calmem))
        print(os.path.join(a.out, name))


if __name__ == "__main__":
    main()
